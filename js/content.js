  // '#' стена, '.' пусто, 'A' якорь, '>' '<' '^' 'v' потоки
  function parseTerrain(rows) {
    const size = rows.length;
    const t = new Uint8Array(size * size);
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) {
        const ch = row[x];
        let v = 0;
        if (ch === '#') v = 1;
        else if (ch === 'A') v = 2;
        else if (ch === '>') v = 3;
        else if (ch === '<') v = 4;
        else if (ch === '^') v = 5;
        else if (ch === 'v') v = 6;
        t[y * size + x] = v;
      }
    });
    return t;
  }
